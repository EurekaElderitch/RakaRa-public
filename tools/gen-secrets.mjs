#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

const engineName = process.argv[2];
if (!engineName) {
  console.error("Usage: node tools/gen-secrets.mjs <engine>");
  process.exit(1);
}

const root = process.cwd();
const secretsPath = path.join(root, "secrets.json");
if (!fs.existsSync(secretsPath)) {
  console.error("✖ secrets.json tidak ada");
  process.exit(1);
}

const raw = fs.readFileSync(secretsPath, "utf8").replace(/^\uFEFF/, "");
const secrets = JSON.parse(raw);
const engineSecrets = secrets[engineName];
if (!engineSecrets) {
  console.error(`✖ Tidak ada secrets untuk '${engineName}'`);
  process.exit(1);
}

const KEY = crypto.randomBytes(32);

function toHex(bytes) {
  return Buffer.from(bytes).toString("hex");
}

function encrypt(str) {
  const buf = Buffer.from(str, "utf8");
  const out = Buffer.alloc(buf.length);
  for (let i = 0; i < buf.length; i++) out[i] = buf[i] ^ KEY[i % KEY.length];
  return toHex(out);
}

const kt = `// Auto-generated by tools/gen-secrets.mjs. Do not edit.
internal object K {
    private fun hex(s: String): ByteArray {
        val out = ByteArray(s.length / 2)
        var i = 0
        while (i < s.length) {
            out[i / 2] = ((Character.digit(s[i], 16) shl 4) or Character.digit(s[i + 1], 16)).toByte()
            i += 2
        }
        return out
    }

    private fun dec(e: ByteArray): String {
        val k = k1 + k2 + k3
        val out = ByteArray(e.size)
        for (i in e.indices) out[i] = (e[i].toInt() xor k[i % k.size].toInt()).toByte()
        return String(out, Charsets.UTF_8)
    }

    private val k1 = hex("${toHex(KEY.slice(0, 10))}")
    private val k2 = hex("${toHex(KEY.slice(10, 20))}")
    private val k3 = hex("${toHex(KEY.slice(20, 32))}")

    val url: String by lazy { dec(hex("${encrypt(engineSecrets.url)}")) }
    val ua: String by lazy { dec(hex("${encrypt(engineSecrets.userAgent || "Mozilla/5.0")}")) }
}
`;

const outFile = path.join(
  root,
  "engines",
  engineName,
  "src/main/kotlin/dev/rakara/engines",
  engineName,
  "K.kt"
);
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, kt);
console.log(`✔ Generated ${path.relative(root, outFile)}`);